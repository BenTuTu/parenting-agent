export function findGuides(
  topic: CareTopic,
  ageMonths?: number | null,
): CareGuideEntry[] {
  return careGuides.filter(
    (g) =>
      g.topic === topic &&
      (ageMonths == null ||
        (ageMonths >= g.minMonth && ageMonths <= g.maxMonth)),
  );
}
